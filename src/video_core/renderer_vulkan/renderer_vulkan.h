namespace Vulkan {

struct TextureInfo {
    u32 width;
    u32 height;
    Pica::PixelFormat format;
    vk::Image image;
    vk::ImageView image_view;
    VmaAllocation allocation;
};

struct ScreenInfo {
    TextureInfo texture;
    Common::Rectangle<f32> texcoords;
    vk::ImageView image_view;
};

struct PresentUniformData {
    std::array<f32, 4 * 4> modelview;
    Common::Vec4f i_resolution;
    Common::Vec4f o_resolution;
    int screen_id_l = 0;
    int screen_id_r = 0;
    int layer = 0;
    int reverse_interlaced = 0;
};
static_assert(sizeof(PresentUniformData) == 112,
              "PresentUniformData does not structure in shader!");

class RendererVulkan : public VideoCore::RendererBase {
    static constexpr std::size_t PRESENT_PIPELINES = 3;

public:
    explicit RendererVulkan(Core::System& system, Pica::PicaCore& pica, Frontend::EmuWindow& window,
                            Frontend::EmuWindow* secondary_window);
    ~RendererVulkan() override;

    [[nodiscard]] VideoCore::RasterizerInterface* Rasterizer() override {
        return &rasterizer;
    }

    void NotifySurfaceChanged(bool second) override;

    void SwapBuffers() override;
    /// Explicit emulation-safe-point readback; never advances guest execution.
    void CaptureOffscreen(void* pixels, const Layout::FramebufferLayout& layout);
    /// Never waits for the GPU while running: completion is polled (Scheduler::IsFree after a
    /// non-blocking MasterSemaphore::Refresh). See RendererBase::PreviewScreens.
    u64 PreviewScreens(const std::array<void*, 2>& pixels,
                       const std::array<Layout::FramebufferLayout, 2>& layouts, u64 frame_id,
                       u64 oldest, bool may_wait) override;
    PreviewStats PreviewStatistics() const override {
        return preview_stats;
    }
    void TryPresent(int timeout_ms, bool is_secondary) override {}

private:
    void ReloadPipeline(Settings::StereoRenderOption render_3d);
    void CompileShaders();
    void BuildLayouts();
    void BuildPipelines();
    void ConfigureFramebufferTexture(TextureInfo& texture,
                                     const Pica::FramebufferConfig& framebuffer);
    void ConfigureRenderPipeline();
    void PrepareRendertarget();
    void LimitFramesAheadOfGpu() override;
    void RenderScreenshot();
    void RenderScreenshotWithStagingCopy();
    struct PreviewSlot {
        Frame frame{};
        VkBuffer buffer{};
        VmaAllocation allocation{};
        void* mapped{};
        u64 size{};
        u64 tick{};
        u64 frame_id{};
        bool pending{}; ///< Copy submitted, completion not yet observed.
        bool ready{};   ///< Copy completed and not yet superseded by a published pair.
    };
    /// Three slots per screen: one being read back, one completed, one free to submit into.
    static constexpr std::size_t PREVIEW_SLOTS = 3;
    void RecordFrameCopy(const Frame& frame, vk::Buffer buffer, u32 width, u32 height);
    void ResizePreviewSlot(PreviewSlot& slot, u32 width, u32 height);
    void DestroyPreviewSlot(PreviewSlot& slot);
    void RetirePreviewSlots();
    PreviewSlot* FreePreviewSlot(u32 stream, bool may_wait);
    PreviewSlot* ReadyPreviewSlot(u32 stream, u64 frame_id);
    void CopyPreviewSlot(const PreviewSlot& slot, void* pixels);
    std::array<std::array<PreviewSlot, PREVIEW_SLOTS>, 2> preview_slots{};
    PreviewStats preview_stats{};
    u64 preview_published = 0; ///< Id of the last pair copied out; never copied again.
    bool TryRenderScreenshotWithHostMemory();
    void PrepareDraw(Frame* frame, const Layout::FramebufferLayout& layout);
    void RenderToWindow(PresentWindow& window, const Layout::FramebufferLayout& layout,
                        bool flipped);

    void DrawScreens(Frame* frame, const Layout::FramebufferLayout& layout, bool flipped);
    void DrawBottomScreen(const Layout::FramebufferLayout& layout,
                          const Common::Rectangle<u32>& bottom_screen);

    void DrawTopScreen(const Layout::FramebufferLayout& layout,
                       const Common::Rectangle<u32>& top_screen);
    void DrawSingleScreen(u32 screen_id, float x, float y, float w, float h,
                          Layout::DisplayOrientation orientation);
    void DrawSingleScreenStereo(u32 screen_id_l, u32 screen_id_r, float x, float y, float w,
                                float h, Layout::DisplayOrientation orientation);

    void ApplySecondLayerOpacity(float alpha);

    void DrawCursor(const Layout::FramebufferLayout& layout);

    void LoadFBToScreenInfo(const Pica::FramebufferConfig& framebuffer, ScreenInfo& screen_info,
                            bool right_eye);
    void FillScreen(Common::Vec3<u8> color, const TextureInfo& texture);

private:
    Memory::MemorySystem& memory;
    Pica::PicaCore& pica;

#ifdef HAVE_LIBRETRO
    LibRetroVKInstance instance;
#else
    Instance instance;
#endif
    Scheduler scheduler;
    RenderManager renderpass_cache;
    PresentWindow main_present_window;
    StreamBuffer vertex_buffer;
    DescriptorUpdateQueue update_queue;
    RasterizerVulkan rasterizer;
    std::unique_ptr<PresentWindow> secondary_present_window_ptr;
    DescriptorHeap present_heap;
    vk::UniquePipelineLayout present_pipeline_layout;
    std::array<vk::Pipeline, PRESENT_PIPELINES> present_pipelines;
    std::array<vk::ShaderModule, PRESENT_PIPELINES> present_shaders;
    std::array<vk::Sampler, 2> present_samplers;
    vk::ShaderModule present_vertex_shader;
    u32 current_pipeline = 0;

    std::array<ScreenInfo, 3> screen_infos{};
    PresentUniformData draw_info{};
    vk::ClearColorValue clear_color{};

    vk::ShaderModule cursor_vertex_shader{};
    vk::ShaderModule cursor_fragment_shader{};
    vk::Pipeline cursor_pipeline{};
    vk::UniquePipelineLayout cursor_pipeline_layout{};
    bool isSecondaryWindow;
    bool secondaryWindowEnabled;
    bool screenRendered;
    u64 previous_game_frame_tick{};
};

} // namespace Vulkan
